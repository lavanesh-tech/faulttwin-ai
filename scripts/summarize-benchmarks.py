#!/usr/bin/env python3
"""Summarize Google Benchmark JSON output for Phase 2.

Usage: scripts/summarize-benchmarks.py <results-dir>

Reads every *.json benchmark file in <results-dir> (not environment.json) and
writes, next to them:
  runs.csv     one row per repetition (raw values, nothing dropped)
  summary.csv  per benchmark: n, median, mean, sample stddev and a 95% percentile
               bootstrap CI (10,000 resamples, fixed seed) of the per-run values,
               as docs/evaluation/metric-definitions.md section 1 requires
  summary.md   the same, readable, plus throughput relative to the
               single-threaded baseline and consumer scaling efficiency

Uses only the Python standard library. Exits 1 if any run reports
invariant_ok != 1 or an error, so a broken run cannot be summarized silently.
"""

import csv
import json
import random
import statistics
import sys
from pathlib import Path

BOOTSTRAP_RESAMPLES = 10_000
BOOTSTRAP_SEED = 20261125
METRICS = [
    "real_time_ms",
    "cpu_time_ms",
    "items_per_second",
    "lat_p50_us",
    "lat_p95_us",
    "lat_p99_us",
    "lat_max_us",
    "processed",
    "rejected",
    "dropped",
    "abandoned",
    "invalid",
    "out_of_order",
    "queue_hwm",
    "producer_s",
    "peak_rss_mib",
]
TIME_TO_MS = {"ns": 1e-6, "us": 1e-3, "ms": 1.0, "s": 1e3}


def bootstrap_ci(values, rng):
    if len(values) < 2:
        return (values[0], values[0]) if values else (None, None)
    means = sorted(
        statistics.fmean(rng.choices(values, k=len(values)))
        for _ in range(BOOTSTRAP_RESAMPLES)
    )
    lo = means[int(0.025 * BOOTSTRAP_RESAMPLES)]
    hi = means[int(0.975 * BOOTSTRAP_RESAMPLES) - 1]
    return lo, hi


def load_runs(results_dir):
    runs, contexts, errors = [], {}, []
    for path in sorted(results_dir.glob("*.json")):
        if path.name == "environment.json":
            continue
        data = json.loads(path.read_text())
        contexts[path.name] = data.get("context", {})
        for b in data.get("benchmarks", []):
            if b.get("run_type") != "iteration":
                continue  # aggregates are recomputed here from raw runs
            if b.get("error_occurred"):
                errors.append(f"{b['name']}: {b.get('error_message')}")
                continue
            scale = TIME_TO_MS[b.get("time_unit", "ns")]
            row = {
                "file": path.name,
                "name": b["run_name"],
                "label": b.get("label", ""),
                "repetition": b.get("repetition_index", 0),
                "real_time_ms": b["real_time"] * scale,
                "cpu_time_ms": b["cpu_time"] * scale,
            }
            for key in METRICS[2:] + ["invariant_ok"]:
                if key in b:
                    row[key] = b[key]
            if row.get("invariant_ok", 1) != 1:
                errors.append(f"{b['name']} repetition {row['repetition']}: invariant_ok=0")
            runs.append(row)
    return runs, contexts, errors


def summarize(runs):
    rng = random.Random(BOOTSTRAP_SEED)
    groups = {}
    for r in runs:
        groups.setdefault(r["name"], []).append(r)
    summary = []
    for name, rows in groups.items():
        entry = {"name": name, "label": rows[0]["label"], "n": len(rows)}
        for m in METRICS:
            values = [float(r[m]) for r in rows if m in r]
            if not values:
                continue
            lo, hi = bootstrap_ci(values, rng)
            entry[f"{m}_median"] = statistics.median(values)
            entry[f"{m}_mean"] = statistics.fmean(values)
            entry[f"{m}_stddev"] = statistics.stdev(values) if len(values) > 1 else 0.0
            entry[f"{m}_ci95_lo"] = lo
            entry[f"{m}_ci95_hi"] = hi
        summary.append(entry)
    return summary


def parse_args(name):
    """'BM_Pipeline/producers:1/consumers:2/...' -> {'producers': 1, ...}."""
    out = {}
    for part in name.split("/")[1:]:
        if ":" in part:
            k, v = part.split(":", 1)
            if v.isdigit():
                out[k] = int(v)
    return out


def fmt(value, digits=1):
    if value is None:
        return "-"
    if abs(value) >= 1e6:
        return f"{value / 1e6:.{digits + 1}f}M"
    if abs(value) >= 1e4:
        return f"{value / 1e3:.{digits}f}k"
    return f"{value:.{digits}f}"


def write_markdown(results_dir, summary, contexts):
    by_name = {s["name"]: s for s in summary}
    baselines = {
        parse_args(s["name"]).get("work"): s
        for s in summary
        if s["name"].startswith("BM_SingleThreadedBaseline/")
    }
    lines = [
        "# Benchmark summary (generated by scripts/summarize-benchmarks.py)",
        "",
        "Values are medians of n repetitions; CI = 95% bootstrap CI of the mean.",
        "Throughput = processed events / wall time. Latency = submit to sink done.",
        "Generated from raw JSON in this directory; see environment.json.",
        "",
    ]
    pipeline = [s for s in summary if s["name"].startswith("BM_Pipeline/")]
    if pipeline:
        lines += [
            "## Experiment 1: pipeline vs single-threaded baseline",
            "",
            "| producers | consumers | capacity | work | n | events/s (median) | 95% CI | "
            "vs baseline | p50 us | p99 us | scaling eff. | rejected | dropped |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for s in sorted(pipeline, key=lambda e: tuple(parse_args(e["name"]).values())):
            a = parse_args(s["name"])
            base = baselines.get(a.get("work"))
            tput = s.get("items_per_second_median")
            rel = (
                f"{tput / base['items_per_second_median']:.2f}x"
                if base and base.get("items_per_second_median")
                else "N/A"
            )
            one = next(
                (
                    o
                    for o in pipeline
                    if parse_args(o["name"])
                    == {**a, "consumers": 1}
                ),
                None,
            )
            scale = (
                f"{tput / (a['consumers'] * one['items_per_second_median']):.2f}"
                if one and one.get("items_per_second_median")
                else "N/A"
            )
            lines.append(
                f"| {a['producers']} | {a['consumers']} | {a['capacity']} | {a['work']} | "
                f"{s['n']} | {fmt(tput)} | {fmt(s.get('items_per_second_ci95_lo'))}-"
                f"{fmt(s.get('items_per_second_ci95_hi'))} | {rel} | "
                f"{fmt(s.get('lat_p50_us_median'))} | {fmt(s.get('lat_p99_us_median'))} | "
                f"{scale} | {fmt(s.get('rejected_median'), 0)} | "
                f"{fmt(s.get('dropped_median'), 0)} |"
            )
        lines.append("")
    rest = [s for s in summary if not s["name"].startswith("BM_Pipeline/")]
    if rest:
        lines += [
            "## Other benchmarks",
            "",
            "| benchmark | label | n | wall ms (median) | events/s (median) | 95% CI | "
            "processed | rejected | dropped | queue hwm | peak RSS MiB |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for s in rest:
            lines.append(
                f"| {s['name']} | {s['label']} | {s['n']} | {fmt(s.get('real_time_ms_median'), 2)} | "
                f"{fmt(s.get('items_per_second_median'))} | "
                f"{fmt(s.get('items_per_second_ci95_lo'))}-{fmt(s.get('items_per_second_ci95_hi'))} | "
                f"{fmt(s.get('processed_median'), 0)} | {fmt(s.get('rejected_median'), 0)} | "
                f"{fmt(s.get('dropped_median'), 0)} | {fmt(s.get('queue_hwm_median'), 0)} | "
                f"{fmt(s.get('peak_rss_mib_median'))} |"
            )
        lines.append("")
    lines += ["## Google Benchmark context per file", ""]
    for file, ctx in contexts.items():
        keys = ["date", "host_name", "num_cpus", "mhz_per_cpu", "cpu_scaling_enabled",
                "library_build_type", "git_commit", "compiler"]
        lines.append(f"- `{file}`: " + ", ".join(f"{k}={ctx.get(k)}" for k in keys if k in ctx))
    (results_dir / "summary.md").write_text("\n".join(lines) + "\n")
    del by_name


def main():
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    results_dir = Path(sys.argv[1])
    runs, contexts, errors = load_runs(results_dir)
    if not runs:
        print(f"no benchmark runs found in {results_dir}", file=sys.stderr)
        return 1
    run_fields = ["file", "name", "label", "repetition"] + METRICS + ["invariant_ok"]
    with open(results_dir / "runs.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=run_fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(runs)
    summary = summarize(runs)
    fields = ["name", "label", "n"] + [
        f"{m}_{stat}" for m in METRICS for stat in ("median", "mean", "stddev", "ci95_lo", "ci95_hi")
    ]
    with open(results_dir / "summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(summary)
    write_markdown(results_dir, summary, contexts)
    print(f"wrote runs.csv ({len(runs)} runs), summary.csv, summary.md to {results_dir}")
    if errors:
        print("ERRORS:", *errors, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
