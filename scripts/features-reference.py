#!/usr/bin/env python3
"""Independent reference for the Phase 4 window statistics (golden fixture generator).

Computes the features of faulttwin.features.v1 for a fixed series with exact rational
arithmetic (fractions.Fraction), so the expected values do not share any floating-point
algorithm with the C++ implementation (Welford, centred slope). Only the final square root
and the conversion to double are inexact.

Usage: scripts/features-reference.py > tests/unit/features/golden_features.inc
"""
from fractions import Fraction
import math

SPAN_MS = 10_000
# (event time in ms, value or None for a missing/stale/invalid entry)
SERIES = [
    (0, 1_000_000.25), (1_000, 1_000_000.75), (2_500, None), (3_000, 1_000_001.5),
    (4_000, 999_999.5), (6_500, 1_000_002.0), (7_000, None), (9_000, 1_000_000.0),
    (11_000, 1_000_003.25), (12_500, 1_000_001.0), (14_000, None), (18_000, 1_000_004.5),
    (21_000, None), (23_500, 1_000_002.75), (24_000, 1_000_000.5),
]
AS_OF_MS = [0, 3_000, 9_000, 9_500, 12_500, 18_000, 21_000, 24_000, 27_000, 40_000]

def features(as_of):
    window = [(t, v) for (t, v) in SERIES if as_of - SPAN_MS < t <= as_of]
    ok = [(Fraction(t, 1000), Fraction(v)) for (t, v) in window if v is not None]
    seen = [t for (t, v) in SERIES if t <= as_of]
    ok_ever = [t for (t, v) in SERIES if t <= as_of and v is not None]
    out = {}
    out["entries"] = len(window)
    out["ok_entries"] = len(ok)
    out["missing_ratio"] = Fraction(len(window) - len(ok), len(window)) if window else None
    if ok_ever:
        out["age_seconds"] = Fraction(as_of - ok_ever[-1], 1000)
    elif seen:
        out["age_seconds"] = Fraction(as_of - seen[0], 1000)
    else:
        out["age_seconds"] = None
    if not ok:
        for k in ("last", "mean", "stddev", "min", "max", "rate", "slope"):
            out[k] = None
        return out
    values = [v for (_, v) in ok]
    n = len(values)
    mean = sum(values) / n
    out["last"] = values[-1]
    out["mean"] = mean
    out["min"] = min(values)
    out["max"] = max(values)
    out["stddev"] = math.sqrt(sum((v - mean) ** 2 for v in values) / (n - 1)) if n >= 2 else None
    dt = ok[-1][0] - ok[0][0]
    out["rate"] = (values[-1] - values[0]) / dt if dt > 0 else None
    if n >= 2:
        tm = sum(t for (t, _) in ok) / n
        sxx = sum((t - tm) ** 2 for (t, _) in ok)
        sxy = sum((t - tm) * (v - mean) for (t, v) in ok)
        out["slope"] = sxy / sxx if sxx > 0 else None
    else:
        out["slope"] = None
    return out

def cpp(x):
    if x is None:
        return "std::nullopt"
    return repr(float(x))

print("// Generated by scripts/features-reference.py (exact rational arithmetic). Do not edit.")
print("// clang-format off")
print("inline constexpr std::int64_t kGoldenSpanMs = %d;" % SPAN_MS)
print("inline const std::vector<GoldenEntry> kGoldenSeries{")
for t, v in SERIES:
    print("    {%d, %s, %s}," % (t, repr(float(v)) if v is not None else "0.0", "true" if v is not None else "false"))
print("};")
print("inline const std::vector<GoldenExpectation> kGoldenExpected{")
for a in AS_OF_MS:
    f = features(a)
    print("    {%d, %d, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s}," % (
        a, f["entries"], f["ok_entries"], cpp(f["last"]), cpp(f["mean"]), cpp(f["stddev"]),
        cpp(f["min"]), cpp(f["max"]), cpp(f["rate"]), cpp(f["slope"]), cpp(f["missing_ratio"]),
        cpp(f["age_seconds"])))
print("};")
print("// clang-format on")
